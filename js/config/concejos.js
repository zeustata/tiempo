export const DEFAULT_CONCEJO_ID = 'gijon';

export function getConcejoById(id) {
  if (!id) return CONCEJOS_ASTURIAS[0];
  const cleanId = String(id).toLowerCase().trim();
  return CONCEJOS_ASTURIAS.find(c => c.id === cleanId) || CONCEJOS_ASTURIAS[0];
}

export function searchConcejos(query) {
  if (!query) return CONCEJOS_ASTURIAS;
  const q = query.toLowerCase().trim();
  return CONCEJOS_ASTURIAS.filter(c => 
    c.name.toLowerCase().includes(q) || 
    c.region.toLowerCase().includes(q) ||
    c.badge.toLowerCase().includes(q) ||
    c.id.toLowerCase().includes(q)
  );
}

/**
 * Cálculo de distancia esférica real sobre la superficie de la Tierra (Fórmula de Haversine)
 */
export function calculateDistanceKm(lat1, lon1, lat2, lon2) {
  const R = 6371; // Radio medio de la Tierra en km
  const dLat = (lat2 - lat1) * Math.PI / 180;
  const dLon = (lon2 - lon1) * Math.PI / 180;
  const a = 
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) * 
    Math.sin(dLon / 2) * Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

export function findClosestConcejo(lat, lon) {
  let closest = CONCEJOS_ASTURIAS[0];
  let minDist = Infinity;

  CONCEJOS_ASTURIAS.forEach(c => {
    const d = calculateDistanceKm(lat, lon, c.lat, c.lon);
    if (d < minDist) {
      minDist = d;
      closest = c;
    }
  });

  return closest;
}